// Package pool предоставляет типобезопасный контейнер для повторного
// использования «тяжёлых» объектов поверх sync.Pool.
//
// В отличие от стандартного sync.Pool, который оперирует any, Pool
// параметризован конкретным типом T и гарантирует сброс состояния
// объекта в Put: вернуть в пул «грязный» объект невозможно.
package pool

import "sync"

// Resetter — ограничение для типов, которые умеют сбрасывать своё
// состояние к нулевому. Метод Reset() обычно генерируется утилитой
// cmd/reset.
type Resetter interface {
	Reset()
}

// Pool — типобезопасный пул объектов одного типа T с методом Reset().
// Нулевое значение использовать нельзя, создавайте через New.
//
// Pool безопасен для конкурентного использования несколькими
// горутинами, как и sync.Pool, на котором он построен.
type Pool[T Resetter] struct {
	pool sync.Pool
}

// New создаёт пул объектов типа T. Функция newFn вызывается, когда в
// пуле нет готового объекта, и должна возвращать новый экземпляр T;
// передавать nil нельзя.
func New[T Resetter](newFn func() T) *Pool[T] {
	return &Pool[T]{
		pool: sync.Pool{
			New: func() any { return newFn() },
		},
	}
}

// Get возвращает объект из пула. Если пул пуст, объект создаётся через
// newFn, переданную в New.
func (p *Pool[T]) Get() T {
	return p.pool.Get().(T)
}

// Put сбрасывает состояние объекта через Reset() и возвращает его в
// пул для повторного использования. После вызова Put объект считается
// принадлежащим пулу — использовать его дальше нельзя.
func (p *Pool[T]) Put(v T) {
	v.Reset()
	p.pool.Put(v)
}
